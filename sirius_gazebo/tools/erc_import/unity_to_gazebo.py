#!/usr/bin/env python3
"""Generate a Gazebo world from an ERC scene of agh-space-systems-rover/unity_sim.

Usage (from this directory, after building fbx2obj, see README.md):
  python3 unity_to_gazebo.py <unity_sim checkout> <sirius_gazebo package dir> [--year 2025]

Produces:
  models/erc<year>_marsyard/  terrain: textured visual mesh + low-poly collision mesh
  models/aruco_tag/           shared tag cube mesh + 5x5_100 textures
  worlds/erc<year>.sdf        terrain, ArUco tags, calibration points, ERC GNSS datum

Frames: Unity is left-handed Y-up; output is ROS/Gazebo FLU (x = Unity z,
y = -Unity x, z = Unity y). The whole world is shifted down by the terrain's
Unity height offset so the ground at the origin is at z ~= 0 (x/y are unchanged).
"""

import argparse
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile

import numpy as np
from PIL import Image

from unity_scene import UnityScene

HERE = os.path.dirname(os.path.abspath(__file__))

# Unity world -> ROS FLU
C = np.array([[0, 0, 1], [-1, 0, 0], [0, 1, 0]], float)
# Unity mirrors X when importing right-handed FBX/OBJ files
F = np.diag([-1.0, 1.0, 1.0])
EARTH_R = 6371000.0  # sphere radius used by unity_sim's GPS.cs

ARUCO_DICTS = {'0': '4X4_50', '1': '5X5_100', '2': 'ORIGINAL_5X5_300'}


def read_obj(path):
    v, vt, vn, faces, header = [], [], [], [], []
    with open(path) as f:
        for line in f:
            if line.startswith('v '):
                v.append([float(x) for x in line.split()[1:4]])
            elif line.startswith('vt '):
                vt.append(line)
            elif line.startswith('vn '):
                vn.append([float(x) for x in line.split()[1:4]])
            elif line.startswith('f '):
                faces.append(line)
            elif line.startswith('mtllib') or line.startswith('usemtl'):
                header.append(line.split()[0])
    return np.array(v), vt, np.array(vn) if vn else None, faces


def write_obj(path, v, vt, vn, faces, mtl=None, material=None):
    with open(path, 'w') as f:
        f.write('# Generated by sirius_gazebo/tools/erc_import/unity_to_gazebo.py\n')
        if mtl:
            f.write(f'mtllib {mtl}\n')
        f.writelines(f'v {a:.5f} {b:.5f} {c:.5f}\n' for a, b, c in v)
        f.writelines(vt)
        if vn is not None:
            f.writelines(f'vn {a:.5f} {b:.5f} {c:.5f}\n' for a, b, c in vn)
        if material:
            f.write(f'usemtl {material}\n')
        f.writelines(faces)


def height_at(v, faces_idx, xy):
    """Highest mesh surface z below (x, y) via a 2D barycentric test; None outside the mesh."""
    a, b, c = v[faces_idx[:, 0]], v[faces_idx[:, 1]], v[faces_idx[:, 2]]
    v0, v1, v2 = b[:, :2] - a[:, :2], c[:, :2] - a[:, :2], np.asarray(xy) - a[:, :2]
    den = v0[:, 0] * v1[:, 1] - v1[:, 0] * v0[:, 1]
    ok = np.abs(den) > 1e-12
    den = np.where(ok, den, 1.0)
    u = (v2[:, 0] * v1[:, 1] - v1[:, 0] * v2[:, 1]) / den
    w = (v0[:, 0] * v2[:, 1] - v2[:, 0] * v0[:, 1]) / den
    hit = ok & (u >= 0) & (w >= 0) & (u + w <= 1)
    if not hit.any():
        return None
    return (a[hit, 2] + u[hit] * (b[hit, 2] - a[hit, 2]) + w[hit] * (c[hit, 2] - a[hit, 2])).max()


def face_indices(faces):
    return np.array([[int(t.split('/')[0]) - 1 for t in line.split()[1:4]] for line in faces])


def convert_fbx(fbx2obj, fbx, out_obj):
    """Run fbx2obj and return the root node's 3x3 transform (assimp, baked into vertices)."""
    res = subprocess.run([fbx2obj, fbx, out_obj], capture_output=True, text=True, check=True)
    for line in res.stdout.splitlines():
        if 'meshes=1' in line and 'T=[' in line:
            nums = line.split('T=[')[1].split(']')[0].replace('|', ' ').split()
            return np.array([float(x) for x in nums]).reshape(3, 3)
    raise RuntimeError(f'Could not find mesh node transform in fbx2obj output:\n{res.stdout}')


def fit_gnss_origin(stations):
    """Fit ENU = Rot(h) * world_xy + t to base stations (like GPS.cs). Returns lat, lon, h, residuals."""
    lat0 = np.mean([s[1] for s in stations])
    lon0 = np.mean([s[2] for s in stations])

    def enu(lat, lon):
        return np.array([math.radians(lon - lon0) * EARTH_R * math.cos(math.radians(lat0)),
                         math.radians(lat - lat0) * EARTH_R])

    W = np.array([s[0] for s in stations])
    E = np.array([enu(s[1], s[2]) for s in stations])
    U, _, Vt = np.linalg.svd((W - W.mean(0)).T @ (E - E.mean(0)))
    R = (U @ Vt).T
    if np.linalg.det(R) < 0:
        raise RuntimeError('GNSS fit needs a reflection; check frame conventions')
    t = E.mean(0) - R @ W.mean(0)
    res = np.linalg.norm(E - (W @ R.T + t), axis=1)
    lat = lat0 + math.degrees(t[1] / EARTH_R)
    lon = lon0 + math.degrees(t[0] / (EARTH_R * math.cos(math.radians(lat0))))
    return lat, lon, math.degrees(math.atan2(R[1, 0], R[0, 0])), res


def fmt_pose(p, rpy=(0, 0, 0)):
    return ' '.join(f'{x:.4f}' for x in (*p, *rpy))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument('unity_sim', help='path to a unity_sim checkout')
    ap.add_argument('package', help='path to the sirius_gazebo package source')
    ap.add_argument('--year', default='2025')
    ap.add_argument('--fbx2obj', default=os.path.join(HERE, 'build', 'fbx2obj'))
    args = ap.parse_args()

    sim = os.path.join(args.unity_sim, 'unity_project', 'unity_sim', 'Assets', 'Simulation')
    scene_dir = os.path.join(sim, 'Scenes', f'ERC{args.year}')
    scene = UnityScene(os.path.join(sim, 'Scenes', f'ERC{args.year}.unity'))
    model_name = f'erc{args.year}_marsyard'
    model_dir = os.path.join(args.package, 'models', model_name)
    tag_dir = os.path.join(args.package, 'models', 'aruco_tag')
    os.makedirs(os.path.join(model_dir, 'meshes'), exist_ok=True)
    os.makedirs(os.path.join(tag_dir, 'meshes'), exist_ok=True)

    objects = scene.objects()
    T_terrain = scene.root_prefab_pose(f'erc{args.year}')
    z_shift = T_terrain[1, 3]  # Unity height of the terrain object; removed from every z

    def to_ros(p_unity):
        return C @ np.asarray(p_unity) - np.array([0, 0, z_shift])

    # --- Terrain meshes -------------------------------------------------------------
    fbx_files = {'visual': f'erc{args.year}.fbx', 'collision': f'erc{args.year}-col.fbx'}
    texture = None
    collision_v = collision_f = None
    with tempfile.TemporaryDirectory() as tmp:
        for kind, fbx in fbx_files.items():
            baked = os.path.join(tmp, f'{kind}.obj')
            N = convert_fbx(args.fbx2obj, os.path.join(scene_dir, fbx), baked)
            # assimp bakes the FBX node transform (cm scale + Blender axis) into the vertices;
            # Unity replaces that node rotation with the instance's own and converts cm -> m.
            v, vt, vn, faces = read_obj(baked)
            Nrot = N / np.linalg.norm(N[0])                    # node rotation only
            unit = 0.01                                        # Unity useFileScale: cm -> m
            M = C @ T_terrain[:3, :3] @ F @ np.linalg.inv(Nrot) * unit
            v_out = v @ M.T + (C @ T_terrain[:3, 3] - np.array([0, 0, z_shift]))
            vn_out = None if vn is None else (vn @ (M / np.linalg.norm(M[0])).T)
            if kind == 'visual':
                with open(baked.replace('.obj', '.mtl')) as f:
                    texture = next(line.split(None, 1)[1].strip() for line in f
                                   if line.startswith('map_Kd'))
                mtl = f'{model_name}.mtl'
                with open(os.path.join(model_dir, 'meshes', mtl), 'w') as f:
                    f.write('newmtl terrain\nKa 1 1 1\nKd 1 1 1\nKs 0.05 0.05 0.05\n'
                            f'illum 1\nmap_Kd {texture}\n')
                write_obj(os.path.join(model_dir, 'meshes', f'{model_name}.obj'),
                          v_out, vt, vn_out, faces, mtl=mtl, material='terrain')
                shutil.copy(os.path.join(scene_dir, texture), os.path.join(model_dir, 'meshes'))
            else:
                # collision: no material; keep normals, DART's ODE mesh reader dereferences them
                write_obj(os.path.join(model_dir, 'meshes', f'{model_name}_collision.obj'),
                          v_out, vt, vn_out, faces)
                collision_v, collision_f = v_out, face_indices(faces)
            print(f'{kind}: {len(v_out)} vertices, bbox min {v_out.min(0).round(2)} '
                  f'max {v_out.max(0).round(2)}')

    with open(os.path.join(model_dir, 'model.config'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<model>
  <name>ERC {args.year} Marsyard</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>
    ERC {args.year} Marsyard terrain, converted from agh-space-systems-rover/unity_sim
    by sirius_gazebo/tools/erc_import. Frame: ROS FLU, x/y identical to the Unity scene.
  </description>
</model>
''')
    with open(os.path.join(model_dir, 'model.sdf'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- Generated by sirius_gazebo/tools/erc_import/unity_to_gazebo.py -->
<sdf version="1.9">
  <model name="{model_name}">
    <static>true</static>
    <link name="link">
      <collision name="collision">
        <geometry>
          <mesh><uri>meshes/{model_name}_collision.obj</uri></mesh>
        </geometry>
        <surface>
          <friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>
        </surface>
      </collision>
      <visual name="visual">
        <geometry>
          <mesh><uri>meshes/{model_name}.obj</uri></mesh>
        </geometry>
      </visual>
    </link>
  </model>
</sdf>
''')

    # --- Sanity check: calibration points must lie on the terrain --------------------
    calib = [(n, to_ros(M[:3, 3])) for n, M, _ in objects if is_calibration_point(n)]
    for n, p in calib:
        h = height_at(collision_v, collision_f, p[:2])
        err = None if h is None else h - p[2]
        print(f'calibration point {n:<7} at {p.round(3)} terrain offset '
              f'{"OUTSIDE" if err is None else f"{err:+.3f} m"}')
        if err is None or abs(err) > 0.1:
            sys.exit('Calibration check failed: terrain does not line up with the scene')

    # --- ArUco tags ------------------------------------------------------------------
    cube_src = os.path.join(sim, 'ArUco', 'ArUcoTagCube.obj')
    v, vt, vn, faces = read_obj(cube_src)
    R_tag = C @ F  # proper rotation (det +1), so face winding is preserved
    write_obj(os.path.join(tag_dir, 'meshes', 'aruco_tag_cube.obj'),
              v @ R_tag.T, vt, vn @ R_tag.T, faces)
    tags = []
    for n, M, m in objects:
        if 'id' not in m or 'dict' not in m:
            continue
        dict_name = ARUCO_DICTS[m['dict']]
        tex_dir = os.path.join(tag_dir, 'textures', dict_name)
        os.makedirs(tex_dir, exist_ok=True)
        png = os.path.join(sim, 'ArUco', 'Textures', dict_name, f'{m["id"]}.png')
        # 9x9 px textures are point-filtered in Unity; upscale so Gazebo's filtering keeps edges
        img = Image.open(png).convert('L')
        img.resize((img.width * 64, img.height * 64), Image.NEAREST).save(
            os.path.join(tex_dir, f'{m["id"]}.png'))
        yaw = math.atan2(*(C @ M[:3, :3] @ np.array([0, 0, 1]))[[1, 0]])
        tags.append(dict(name=n, id=m['id'], dict=dict_name, pose=to_ros(M[:3, 3]), yaw=yaw,
                         size=float(m.get('size', 0.1)), height=float(m.get('height', 0.5))))
    with open(os.path.join(tag_dir, 'model.config'), 'w') as f:
        f.write('''<?xml version="1.0"?>
<model>
  <name>ArUco tag (unity_sim)</name>
  <version>1.0</version>
  <description>Shared mesh and textures for ERC ArUco tag posts. Instances are defined
  inline in the world, since each one uses a different texture.</description>
</model>
''')

    # --- GNSS datum --------------------------------------------------------------------
    stations = [(to_ros(M[:3, 3])[:2], float(m['latitude']), float(m['longitude']),
                 float(m.get('altitude', 0))) for n, M, m in objects if 'latitude' in m]
    lat, lon, heading, res = fit_gnss_origin([s[:3] for s in stations])
    altitude = np.mean([s[3] for s in stations])
    print(f'GNSS origin lat={lat:.8f} lon={lon:.8f} alt={altitude:.1f}; world x-axis is '
          f'{heading:.2f} deg CCW from East; station residuals {res.round(2)} m')

    write_world(args, model_name, tags, calib, lat, lon, altitude, heading,
                collision_v[:, 2].min())


def is_calibration_point(name):
    """Calibration spheres under CalibrationPoints are named 'S (1)', 'W (6)', ..."""
    return re.fullmatch(r'[SW] \(\d+\)', name) is not None


def write_world(args, model_name, tags, calib, lat, lon, alt, heading, terrain_min_z):
    tag_models = []
    for t in tags:
        s, h = t['size'], t['height']
        tag_models.append(f'''
    <!-- {t['name']}: {t['dict']} id {t['id']} -->
    <model name="aruco_{t['id']}">
      <static>true</static>
      <pose>{fmt_pose(t['pose'], (0, 0, t['yaw']))}</pose>
      <link name="link">
        <collision name="pole_collision">
          <pose>0 0 {h / 2:.4f} 0 0 0</pose>
          <geometry><cylinder><radius>0.015</radius><length>{h:.4f}</length></cylinder></geometry>
        </collision>
        <visual name="pole">
          <pose>0 0 {h / 2:.4f} 0 0 0</pose>
          <geometry><cylinder><radius>0.015</radius><length>{h:.4f}</length></cylinder></geometry>
          <material>
            <ambient>0.3 0.3 0.3 1</ambient><diffuse>0.3 0.3 0.3 1</diffuse>
          </material>
        </visual>
        <collision name="cube_collision">
          <pose>0 0 {h + s / 2:.4f} 0 0 0</pose>
          <geometry><box><size>{s:.4f} {s:.4f} {s:.4f}</size></box></geometry>
        </collision>
        <visual name="cube">
          <pose>0 0 {h + s / 2:.4f} 0 0 0</pose>
          <geometry>
            <mesh>
              <uri>model://aruco_tag/meshes/aruco_tag_cube.obj</uri>
              <scale>{s:.4f} {s:.4f} {s:.4f}</scale>
            </mesh>
          </geometry>
          <material>
            <diffuse>1 1 1 1</diffuse>
            <ambient>1 1 1 1</ambient>
            <specular>0 0 0 1</specular>
            <pbr><metal>
              <albedo_map>model://aruco_tag/textures/{t['dict']}/{t['id']}.png</albedo_map>
              <roughness>1.0</roughness>
              <metalness>0.0</metalness>
            </metal></pbr>
          </material>
        </visual>
      </link>
    </model>''')

    calib_models = []
    for n, p in calib:
        key = n.replace(' ', '').replace('(', '_').replace(')', '')
        calib_models.append(f'''
    <!-- Unity calibration point {n} (visual only) -->
    <model name="calibration_{key}">
      <static>true</static>
      <pose>{fmt_pose(p)}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><sphere><radius>0.05</radius></sphere></geometry>
          <material>
            <ambient>1 0.1 0.1 1</ambient><diffuse>1 0.1 0.1 1</diffuse>
          </material>
        </visual>
      </link>
    </model>''')

    world = f'''<?xml version="1.0"?>
<!-- ERC {args.year} Marsyard, generated from agh-space-systems-rover/unity_sim
     (scene ERC{args.year}.unity) by sirius_gazebo/tools/erc_import/unity_to_gazebo.py.
     Do not edit by hand; regenerate instead.

     Frame: x/y identical to the Unity scene (ROS FLU: x = Unity z, y = -Unity x);
     z shifted so the ground at the origin (start point S) is at ~0.
     GNSS: spherical coordinates fitted to the scene's GPS base stations, so /gps/fix
     matches the coordinates used at the competition. -->
<sdf version="1.9">
  <world name="erc{args.year}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-magnetometer-system" name="gz::sim::systems::Magnetometer"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>

    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{lat:.8f}</latitude_deg>
      <longitude_deg>{lon:.8f}</longitude_deg>
      <elevation>{alt:.2f}</elevation>
      <heading_deg>{heading:.3f}</heading_deg>
    </spherical_coordinates>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.75 0.65 0.55 1</background>
      <shadows>true</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.3 -0.85</direction>
    </light>

    <include>
      <uri>model://{model_name}</uri>
      <name>marsyard</name>
      <pose>0 0 0 0 0 0</pose>
    </include>

    <!-- Fallback ground below the lowest point of the yard, so nothing falls forever -->
    <model name="ground_plane">
      <static>true</static>
      <pose>0 0 {terrain_min_z - 0.1:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>300 300</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>300 300</size></plane></geometry>
          <material>
            <ambient>0.55 0.4 0.3 1</ambient><diffuse>0.55 0.4 0.3 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
{''.join(tag_models)}
{''.join(calib_models)}
  </world>
</sdf>
'''
    path = os.path.join(args.package, 'worlds', f'erc{args.year}.sdf')
    with open(path, 'w') as f:
        f.write(world)
    print(f'wrote {path} ({len(tags)} ArUco tags, {len(calib)} calibration points)')


if __name__ == '__main__':
    main()
